await mkdir(imageDirectory, { recursive: true });

const extensions = {};
const credits = [];
const today = new Date().toISOString().slice(0, 10);

for (const day of days) {
  for (const step of day.steps) {
    const visual = TITLE_TO_VISUAL[step.title];
    if (!visual) throw new Error(`No visual for: ${step.title}`);
    const stem = getStepImageBasename(step);
    const destName = `${stem}.jpg`;
    await copyFile(resolve(generatedDir, visual), resolve(imageDirectory, destName));
    extensions[stem] = "jpg";
    credits.push({
      stepId: step.id,
      localFile: `assets/images/${destName}`,
      title: `${VISUAL_NOTE[visual] ?? visual} — ${step.title}`,
      creator: "generated place visual",
      license: "personal itinerary use",
      licenseUrl: "",
      sourceUrl: visual,
      retrievedAt: today,
    });
    console.log(`${step.id} ← ${visual}`);
  }
}

// Also keep a clear shinsegae copy available if we later split the shopping step
